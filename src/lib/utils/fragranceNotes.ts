const ingredientLookup = new Map<string, NoteEntry>();
for (const [english, arabic, image] of ingredientEntries) {
  const entry = { english, arabic, image };
  ingredientLookup.set(english.toLowerCase(), entry);
  ingredientLookup.set(arabic, entry);
}

/** Shows the first listed ingredient while retaining the complete source value. */
export function getFragranceNotePresentation(value: string, arabic: boolean) {
  const source = value.replace(/^[^:]+:\s*/, "");
  const first = source.split(/[,،;]|\s+(?:and|with)\s+|\s+و\s+/i)[0].replace(/[.\s]+$/, "").trim();
  const entry = ingredientLookup.get(first.toLowerCase());
  return {
    original: entry?.english ?? first,
    label: arabic ? entry?.arabic ?? first : entry?.english ?? first,
    image: entry ? `/images/fragrance-notes/${entry.image}.webp` : null,
    allNotes: value,
  };
}

/** Some houses publish key ingredients without a top/heart/base pyramid. */
export function parseFragranceKeyNotes(raw?: string): string[] {
  if (!raw || !/^(?:Key notes|النفحات الرئيسية):\s*/i.test(raw)) return [];
  return raw.replace(/^(?:Key notes|النفحات الرئيسية):\s*/i, "")
    .split(/[,،]/).map((note) => note.trim()).filter(Boolean).slice(0, 3);
}
